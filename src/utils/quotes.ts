/**
 * One element of a list, at random.
 *
 * @param {T[]} items - The list to draw from; must not be empty.
 * @returns {T} One of its elements.
 */
export function pick<T>(items: T[]): T {
  return items[Math.floor(Math.random() * items.length)];
}
